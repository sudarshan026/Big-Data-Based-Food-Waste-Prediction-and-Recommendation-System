"""
PySpark Big Data pipeline routes for FoodWaste Analytics.
Provides endpoints to trigger PySpark distributed processing, inspect stages, and fetch aggregations.
"""

from flask import Blueprint, jsonify
from app.spark.processor import SparkProcessor

spark_bp = Blueprint('spark', __name__, url_prefix='/api/spark')
_spark_processor = None


def get_processor():
    global _spark_processor
    if _spark_processor is None:
        _spark_processor = SparkProcessor()
    return _spark_processor


@spark_bp.route('/process', methods=['POST'])
def run_pipeline():
    """Trigger the PySpark Big Data cleaning, transformation, and aggregation pipeline."""
    processor = get_processor()
    result = processor.process()
    return jsonify(result)


@spark_bp.route('/status', methods=['GET'])
def get_pipeline_status():
    """Get the status of the most recent PySpark pipeline execution."""
    processor = get_processor()
    return jsonify(processor.get_status())


@spark_bp.route('/results', methods=['GET'])
def get_pipeline_results():
    """Retrieve all aggregated datasets generated by the Big Data pipeline."""
    processor = get_processor()
    return jsonify(processor.get_aggregated_results())

